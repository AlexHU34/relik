const RECENT_KEY = 'relik.emoji.recent';

export function getRecentEmoji() {
  try {
    const arr = JSON.parse(localStorage.getItem(RECENT_KEY) || '[]');
    return Array.isArray(arr) ? arr.filter((e) => typeof e === 'string').slice(0, 24) : [];
  } catch (e) {
    return [];
  }
}

export function pushRecentEmoji(emoji) {
  try {
    const arr = getRecentEmoji().filter((e) => e !== emoji);
    arr.unshift(emoji);
    localStorage.setItem(RECENT_KEY, JSON.stringify(arr.slice(0, 24)));
  } catch (e) { /* ignore */ }
}
